CREATE TABLE attendance_audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL,
    actor_employee_id BIGINT,
    actor_name VARCHAR(150) NOT NULL,
    action VARCHAR(40) NOT NULL,
    detail VARCHAR(1000) NOT NULL,
    attendance_date DATE,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_attendance_audit_employee
        FOREIGN KEY (employee_id) REFERENCES employees(id)
);

CREATE INDEX idx_attendance_audit_employee
    ON attendance_audit_logs(employee_id, created_at);

CREATE TABLE attendance_selfies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL,
    attendance_date DATE NOT NULL,
    content_type VARCHAR(80) NOT NULL,
    image_data BYTEA NOT NULL,
    captured_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_attendance_selfie_employee
        FOREIGN KEY (employee_id) REFERENCES employees(id),
    CONSTRAINT uk_attendance_selfie_day UNIQUE (employee_id, attendance_date)
);
